/**
 * Fifth Schedule 1(e) bank/financial-institution merger QP.
 * Out of scope for resident-individual Relief Interview / Calculator UX.
 * Kept out of approved catalogs; this helper blocks any leftover row.
 */

export const BANK_MERGER_QP_GROUP = "qp_bank_merger";

export function isBankMergerQpGroup(compareGroupId: string): boolean {
  return compareGroupId === BANK_MERGER_QP_GROUP;
}
